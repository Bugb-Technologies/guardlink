/**
 * A note another tool appends inside the GuardLink block, after GuardLink's
 * own footer line, survives `guardlink sync`.
 *
 * Workspace tooling writes one line per linked member there ("Workspace <name>:
 * this is member <member> ..."). Sync rewrote the whole block and deleted it,
 * so every sync turned a tracked instruction file into a diff that an agent
 * then restored by hand. GuardLink has never generated anything after its
 * footer, so what sits there can only be another writer's, and it is kept
 * verbatim. Everything before the footer is still GuardLink's to rewrite.
 */
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parseProject } from '../src/parser/parse-project.js';
import { initProject, syncAgentFiles, replaceOrAppend } from '../src/init/index.js';
import { findAgentConfigDiagnostics } from '../src/parser/validate.js';

const NOTE = 'Workspace shop: this is member orders. Use flat, globally unique ids across members. Cross-service questions use the app-folder graph at /work/shop; bravos workspace show lists services and references.';
const FOOTER = '_Generated by `guardlink sync`';

/** The exact edit the workspace tool makes: the note after the block body, before the end marker. */
function appendNote(text: string, note: string): string {
  return text.replace(/(<!-- guardlink:begin -->)([\s\S]*?)(<!-- guardlink:end -->)/,
    (_all, start, body: string, end) => `${start}${body.replace(/^Workspace [^\r\n]*(?:\r?\n|$)/gm, '').trimEnd()}\n\n${note}\n\n${end}`);
}

function block(text: string): string {
  const begin = text.indexOf('<!-- guardlink:begin -->');
  return text.slice(begin, text.indexOf('<!-- guardlink:end -->', begin));
}

describe('sync keeps a note appended after the GuardLink footer', () => {
  let root: string;

  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'guardlink-tail-'));
    await mkdir(join(root, 'src'), { recursive: true });
    await writeFile(join(root, 'package.json'), '{"name":"orders","version":"1.0.0"}\n');
    await writeFile(join(root, 'src', 'auth.ts'),
      '/**\n * @asset App.Auth (#auth) -- "auth"\n * @threat SQLi (#sqli) [high] cwe:CWE-89 -- "sqli"\n'
      + ' * @exposes #auth to #sqli [high] -- "concatenated"\n */\nexport function login() {}\n');
    initProject({ root, mode: 'inline', agentIds: ['claude', 'codex'] });
    const { model } = await parseProject({ root, project: 'orders' });
    syncAgentFiles({ root, model });
  });

  afterEach(async () => { await rm(root, { recursive: true, force: true }); });

  it('the member note is still there, once, after a sync', async () => {
    for (const file of ['CLAUDE.md', 'AGENTS.md']) {
      await writeFile(join(root, file), appendNote(await readFile(join(root, file), 'utf-8'), NOTE));
    }
    const { model } = await parseProject({ root, project: 'orders' });
    syncAgentFiles({ root, model });
    for (const file of ['CLAUDE.md', 'AGENTS.md']) {
      const text = await readFile(join(root, file), 'utf-8');
      expect(block(text), file).toContain(NOTE);
      expect(text.split(NOTE).length - 1, file).toBe(1);
      expect(block(text).indexOf(NOTE), file).toBeGreaterThan(block(text).indexOf(FOOTER));
    }
  });

  it('the note is byte-stable: sync and the workspace tool agree on its layout', async () => {
    const path = join(root, 'CLAUDE.md');
    const noted = appendNote(await readFile(path, 'utf-8'), NOTE);
    await writeFile(path, noted);
    const { model } = await parseProject({ root, project: 'orders' });
    syncAgentFiles({ root, model });
    expect(await readFile(path, 'utf-8')).toBe(noted);
    syncAgentFiles({ root, model });
    expect(await readFile(path, 'utf-8')).toBe(noted);
    // And the workspace tool rewriting its note after a sync changes nothing either.
    expect(appendNote(await readFile(path, 'utf-8'), NOTE)).toBe(noted);
  });

  it('a kept note does not make the block read as stale', async () => {
    await writeFile(join(root, 'CLAUDE.md'), appendNote(await readFile(join(root, 'CLAUDE.md'), 'utf-8'), NOTE));
    const { model } = await parseProject({ root, project: 'orders' });
    syncAgentFiles({ root, model });
    const { model: synced } = await parseProject({ root, project: 'orders' });
    expect(findAgentConfigDiagnostics(synced).filter(d => d.code?.startsWith('agent-block'))).toEqual([]);
  });

  it('a removed note is not resurrected', async () => {
    const path = join(root, 'CLAUDE.md');
    const clean = await readFile(path, 'utf-8');
    await writeFile(path, appendNote(clean, NOTE));
    const { model } = await parseProject({ root, project: 'orders' });
    syncAgentFiles({ root, model });
    await writeFile(path, clean);
    syncAgentFiles({ root, model });
    expect(await readFile(path, 'utf-8')).toBe(clean);
  });

  it('an edit before the footer is still GuardLink\'s to rewrite', async () => {
    const path = join(root, 'CLAUDE.md');
    const clean = await readFile(path, 'utf-8');
    await writeFile(path, clean.replace('**What you owe it back**', 'HAND EDIT\n\n**What you owe it back**'));
    const { model } = await parseProject({ root, project: 'orders' });
    syncAgentFiles({ root, model });
    expect(await readFile(path, 'utf-8')).toBe(clean);
  });
});

describe('replaceOrAppend carries the tail only between GuardLink blocks', () => {
  const fresh = `<!-- guardlink:begin -->\n<!-- guardlink:stamp annotation_hash=b -->\nbody v2\n\n${FOOTER}, which rewrites this block._\n\n<!-- guardlink:end -->\n`;

  it('keeps a tail after the footer, and the text outside the markers', () => {
    const old = `# Mine\n\n<!-- guardlink:begin -->\n<!-- guardlink:stamp annotation_hash=a -->\nbody v1\n\n${FOOTER}, which rewrites this block._\n\nnote one\nnote two\n\n<!-- guardlink:end -->\n\n## After\n`;
    expect(replaceOrAppend(old, fresh)).toBe(`# Mine\n\n<!-- guardlink:begin -->\n<!-- guardlink:stamp annotation_hash=b -->\nbody v2\n\n${FOOTER}, which rewrites this block._\n\nnote one\nnote two\n\n<!-- guardlink:end -->\n\n## After\n`);
  });

  it('an old block with no footer (an older GuardLink, or another format) carries nothing', () => {
    const old = '<!-- guardlink:begin -->\n## Live Threat Model Context\nstale\n<!-- guardlink:end -->\n';
    expect(replaceOrAppend(old, fresh)).toBe(fresh);
  });

  it('a new block with no footer (the Cursor rule form) takes no tail', () => {
    const old = `<!-- guardlink:begin -->\nbody\n${FOOTER}, x._\n\nnote\n<!-- guardlink:end -->\n`;
    const rule = '<!-- guardlink:begin -->\nrule body\n<!-- guardlink:end -->\n';
    expect(replaceOrAppend(old, rule)).toBe(rule);
  });
});
